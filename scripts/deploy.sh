#!/usr/bin/env bash
# Build, install, stamp and restart Omniscience, then say which build is live.
#
# One command, so "is what I see the thing I just changed?" has one answer. The stamp is
# written into the installed copy at deploy time, because Hermes installs a *copy* of this
# tree: an installed plugin has no .git, so only a stamp written here can say which commit
# it came from.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
INSTALLED="${HERMES_PLUGIN_DIR:-$HOME/.hermes/plugins/omniscience}"
PORT="${OMNI_PORT:-8797}"
DATADIR="${OMNI_DATA_DIR:-$HOME/.hermes/plugin-data/omniscience}"

cd "$REPO_ROOT"

echo "==> Building the viewer"
bash scripts/bundle-viewer.sh

VERSION="$(grep -m1 '^version:' plugin.yaml | cut -d: -f2- | tr -d '"' | xargs)"
COMMIT="$(git rev-parse HEAD)"
COMMIT_DATE="$(git log -1 --format=%cI)"
DIRTY="false"
# Build outputs are regenerated by this script, so they must not make every deploy look modified.
if [ -n "$(git status --porcelain -- . ':!viewer_app/static' ':!viewer_app/BUILD_INFO.json' ':!web/dist')" ]; then
  DIRTY="true"
fi
BUILT_AT="$(date -Iseconds)"
# Pre-release numbering: the manifest holds the release this tree is heading to (1.0.0) and every
# build says how far past it is. Two deploys can never carry the same name, and the number only
# resets when a release is actually tagged.
COMMITS="$(git rev-list --count HEAD)"
DISPLAY="${VERSION}-dev.${COMMITS}"

echo "==> Installing into $INSTALLED"
hermes plugins update omniscience --force 2>&1 | tail -2

# The installer re-applies local modifications on top of the update, which means a file edited
# in the installed copy can keep its old content while the repo moves on. Overlay the built tree
# so "installed" means "this tree", not "mostly this tree".
if command -v rsync >/dev/null 2>&1; then
  echo "==> Syncing the built tree over the install"
  rsync -a --exclude '.git' --exclude 'node_modules' --exclude '__pycache__' \
    "$REPO_ROOT/viewer/" "$INSTALLED/viewer/"
  # --delete on the assets only: a stale index-*.js left beside the new one is how a page ends up
  # pointing at a bundle nobody built.
  rsync -a --delete --exclude '.git' --exclude 'node_modules' --exclude '__pycache__' \
    "$REPO_ROOT/viewer_app/static/assets/" "$INSTALLED/viewer_app/static/assets/"
  rsync -a --exclude '.git' --exclude 'node_modules' --exclude '__pycache__' \
    "$REPO_ROOT/viewer_app/" "$INSTALLED/viewer_app/"
else
  echo "==> rsync missing; copying the two packages with cp -a"
  cp -a "$REPO_ROOT/viewer/." "$INSTALLED/viewer/"
  cp -a "$REPO_ROOT/viewer_app/." "$INSTALLED/viewer_app/"
fi

# The manifest is the version the user reads in `hermes plugins list`; the installer keeps a
# locally modified copy, so put ours back or the chip and the list disagree.
cp "$REPO_ROOT/plugin.yaml" "$INSTALLED/plugin.yaml"

python3 - "$INSTALLED" "$VERSION" "$COMMIT" "$COMMIT_DATE" "$BUILT_AT" "$DIRTY" "$REPO_ROOT/viewer_app" "$INSTALLED/viewer_app" "$DISPLAY" "$INSTALLED/viewer" <<'PY'
import json, pathlib, sys
installed, version, commit, commit_date, built_at, dirty, viewer_app, installed_viewer_app, display, installed_viewer = sys.argv[1:11]
payload = {
    "version": display,
    "release": version,
    "commit": commit,
    "commit_date": commit_date,
    "built_at": built_at,
    "dirty": dirty == "true",
    "channel": "dev" if "-dev." in display else "release",
}
# The viewer imports from `$INSTALLED/viewer` (PYTHONPATH), not `viewer_app`, so that is the
# tree whose BUILD_INFO decides what the chip reads. Stamping only viewer_app left the chip
# reporting the install checkout's own HEAD — the wrong commit on a correct deploy.
for target in (
    pathlib.Path(installed),
    pathlib.Path(viewer_app),
    pathlib.Path(installed_viewer_app),
    pathlib.Path(installed_viewer),
):
    if target.is_dir():
        (target / "BUILD_INFO.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        print(f"==> Stamped {target}")
PY

echo "==> Restarting the viewer on :$PORT"
PID="$(ss -ltnp 2>/dev/null | grep -E ":$PORT[[:space:]]" | grep -o 'pid=[0-9]*' | cut -d= -f2 | head -1 || true)"
if [ -n "${PID:-}" ]; then
  PYTHONPATH_SAVED="$(tr '\0' '\n' < "/proc/$PID/environ" 2>/dev/null | grep '^PYTHONPATH=' | cut -d= -f2- || true)"
  kill "$PID" 2>/dev/null || true
  sleep 2
fi
mkdir -p "$DATADIR"
# A bare `python3` is not safe here: this shell has inherited an interpreter whose standard library
# cannot even import asyncio (a half-updated toolchain), and the restart took the site down. Test
# each candidate before using it, and try the next one if the port does not answer.
pick_python() {
  for candidate in "${OMNI_PYTHON:-}" python3 /usr/bin/python3 python3.13 /usr/bin/python3.13 "$HOME/.hermes/venv/bin/python"; do
    [ -n "$candidate" ] || continue
    # Resolve to an absolute path: the same name resolved to a different interpreter inside the
    # setsid subshell, which is how a broken 3.14 toolchain took the site down.
    resolved="$(command -v "$candidate" 2>/dev/null || true)"
    [ -n "$resolved" ] || continue
    if "$resolved" -c 'import asyncio, logging, sqlite3, json' >/dev/null 2>&1; then
      printf '%s' "$resolved"
      return 0
    fi
  done
  return 1
}

start_viewer() {
  PYTHONPATH="${PYTHONPATH_SAVED:-$INSTALLED/viewer}" setsid nohup "$1" -m omniscience_viewer \
    --db "$DATADIR/events.db" \
    --static "$INSTALLED/viewer_app/static" \
    --port "$PORT" --host 127.0.0.1 \
    >> "$DATADIR/viewer.log" 2>&1 &
  for _ in $(seq 1 24); do
    # Any HTTP answer means the server is up. `curl -f` treated a 401 as failure, so a healthy
    # viewer that wants a token was reported dead and then killed.
    code="$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/" || true)"
    if [ -n "${code:-}" ] && [ "$code" != "000" ]; then return 0; fi
    sleep 0.5
  done
  return 1
}

STARTED=""
for candidate in $(pick_python) /usr/bin/python3 python3; do
  [ -n "$candidate" ] || continue
  echo "==> Starting the viewer with $candidate"
  if start_viewer "$candidate"; then
    LIVE_PID="$(ss -ltnp 2>/dev/null | grep -E ":$PORT[[:space:]]" | grep -o 'pid=[0-9]*' | cut -d= -f2 | head -1 || true)"
    if [ -n "${PID:-}" ] && [ "${LIVE_PID:-}" = "$PID" ]; then
      echo "    the port is still owned by the old process; waiting"
      sleep 2
      continue
    fi
    STARTED="$candidate"
    break
  fi
  echo "    $candidate did not bring the port up; trying the next"
  NEWPID="$(ss -ltnp 2>/dev/null | grep -E ":$PORT[[:space:]]" | grep -o 'pid=[0-9]*' | cut -d= -f2 | head -1 || true)"
  [ -n "${NEWPID:-}" ] && kill "$NEWPID" 2>/dev/null || true
  sleep 1
done
[ -n "$STARTED" ] || { echo "FAIL: no interpreter could start the viewer; see $DATADIR/viewer.log"; exit 1; }

for _ in $(seq 1 20); do
  if curl -sf -o /dev/null "http://127.0.0.1:$PORT/"; then break; fi
  sleep 0.5
done

echo
echo "==> Live build:"
"$STARTED" "$SCRIPT_DIR/live-build.py" "$PORT" "$DATADIR/viewer-token" || true
echo
echo "==> Checking what the server actually serves"
"$STARTED" "$SCRIPT_DIR/verify-served.py" "$PORT" "$DATADIR/viewer-token" || exit 1
echo "  reload the page once: the chip in the header must show that same line."
