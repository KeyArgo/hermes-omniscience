#!/usr/bin/env bash
#
# demo-home.sh — create an ISOLATED Hermes home to exercise the omniscience plugin
# without ever touching the real ~/.hermes / hermes home.
#
# The home lives at ${OMNI_DEMO_HOME:-<repo>/.demo-home} and gets:
#   * config.yaml   : model provider "fleet" (http://127.0.0.1:8890/v1, no key),
#                     plugins.enabled: [omniscience], onboarding completed.
#   * plugins/omniscience -> <repo>   (symlink)
#
# It is idempotent: re-running only fills in what is missing and never clobbers an
# existing config.yaml or a real (non-symlink) plugin directory. It REFUSES to run if
# the resolved target is the user's real ~/.hermes or any path ending in /.hermes.
#
# This script only sets up files. It does NOT invoke hermes. scripts/real-run.sh does.
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
PLUGIN_SRC="$REPO"

# Absolute, symlink-resolved path for $1. GNU `readlink -m` is not on macOS and BSD
# `readlink` has no -m/-f either; use Python when present, then a plain-cd fallback.
abspath() {
  if command -v python3 >/dev/null 2>&1; then
    python3 -c 'import os, sys; print(os.path.realpath(sys.argv[1]))' "$1"
    return 0
  fi
  local p="$1" rest="" base
  case "$p" in /*) ;; *) p="$PWD/$p" ;; esac
  while [ ! -e "$p" ] && [ "$p" != "/" ]; do
    rest="/${p##*/}$rest"
    p="${p%/*}"
    [ -n "$p" ] || p="/"
  done
  base="$(cd -P -- "$p" 2>/dev/null && pwd -P)" || base="$p"
  printf '%s%s\n' "$base" "$rest"
}

log()  { printf '[demo-home] %s\n' "$*"; }
warn() { printf '[demo-home] WARN: %s\n' "$*" >&2; }
die()  { printf '[demo-home] REFUSED: %s\n' "$*" >&2; exit 2; }

# ---------------------------------------------------------------- resolve target
raw="${OMNI_DEMO_HOME:-$REPO/.demo-home}"
# Expand a leading ~ against $HOME (abspath does not do it for us).
case "$raw" in
  "~")   raw="$HOME" ;;
  "~/"*) raw="$HOME/${raw#\~/}" ;;
esac
ABS="$(abspath "$raw")"

# ---------------------------------------------------------------- safety rail
# Never let an isolated demo home collide with a real Hermes profile.
if [ -z "${HOME:-}" ]; then
  die "\$HOME is unset — cannot verify the ~/.hermes guard."
fi
[ "$ABS" = "$HOME/.hermes" ] && die "refusing to use the real Hermes home: $ABS"
case "$ABS" in
  /.hermes|*/.hermes) die "refusing: target ends in /.hermes: $ABS" ;;
esac
[ "$ABS" = "/" ] && die "refusing: target resolves to the filesystem root."
[ "$ABS" = "$HOME" ] && die "refusing: target resolves to \$HOME: $ABS"

# ---------------------------------------------------------------- create home
if [ -e "$ABS" ] && [ ! -d "$ABS" ]; then
  die "target exists but is not a directory: $ABS"
fi

if [ -d "$ABS" ]; then
  log "home already exists: $ABS"
else
  mkdir -p "$ABS"
  log "created isolated home: $ABS"
fi

# ---------------------------------------------------------------- config.yaml
cfg="$ABS/config.yaml"
if [ -e "$cfg" ]; then
  log "config.yaml already present (left unchanged): $cfg"
else
  cat > "$cfg" <<'YAML'
# Isolated Hermes home for the Omniscience e2e demo.
# Generated by scripts/demo-home.sh — safe to delete (rm -r); nothing else points here.
model:
  default: DeepSeek-V4.1-Flash-1017
  provider: fleet
providers:
  fleet:
    name: Spark A/B DeepSeek
    base_url: http://127.0.0.1:8890/v1
    api_key: no-key-required
    discover_models: false
    models:
      DeepSeek-V4.1-Flash-1017:
        context_length: 524288
    default_model: DeepSeek-V4.1-Flash-1017

plugins:
  enabled:
    - omniscience

onboarding:
  completed: true
YAML
  log "wrote config.yaml: $cfg"
fi

# ---------------------------------------------------------------- plugin symlink
mkdir -p "$ABS/plugins"
link="$ABS/plugins/omniscience"
if [ -L "$link" ]; then
  cur="$(readlink "$link")"
  if [ "$cur" = "$PLUGIN_SRC" ]; then
    log "plugin already linked: plugins/omniscience -> $cur"
  else
    ln -sfn -- "$PLUGIN_SRC" "$link"
    log "re-pointed plugin symlink: $cur  ->  $PLUGIN_SRC"
  fi
elif [ -e "$link" ]; then
  warn "plugins/omniscience exists and is not a symlink — leaving it alone."
  warn "remove it manually if you want the demo symlink ($PLUGIN_SRC)."
else
  ln -s -- "$PLUGIN_SRC" "$link"
  log "linked plugin: plugins/omniscience -> $PLUGIN_SRC"
fi
[ -e "$PLUGIN_SRC" ] || warn "symlink target does not exist yet: $PLUGIN_SRC (dangling until the plugin lane lands)."

log "done. Run the real e2e with: $(dirname "$0")/real-run.sh"
