// Generates web/src/theme/pass10-paper.gen.css: light-face overrides for every rule that
// hard-codes a dark background, a dark border or a near-white text colour. Re-run after CSS
// changes: `node web/scripts/gen-paper.cjs`. The output is committed; review its diff.
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(SRC, 'theme', 'pass10-paper.gen.css');
const P = ':root[data-theme="paper"]';

const files = [path.join(SRC, 'styles.css')]
  .concat(fs.readdirSync(path.join(SRC, 'components')).filter((f) => f.endsWith('.css')).map((f) => path.join(SRC, 'components', f)))
  .concat(fs.readdirSync(path.join(SRC, 'theme')).filter((f) => /^pass[0-9]-.*\.css$/.test(f)).sort().map((f) => path.join(SRC, 'theme', f)));

function rgbOf(lit) {
  let m = lit.match(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i);
  if (m) {
    let h = m[1];
    if (h.length === 3) h = h.split('').map((c) => c + c).join('');
    return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  }
  m = lit.match(/^rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)/i);
  return m ? [+m[1], +m[2], +m[3]] : null;
}
const lum = ([r, g, b]) => (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
const COLOR = /#[0-9a-f]{3,6}\b|rgba?\([^)]*\)/gi;
const isNeutral = ([r, g, b]) => Math.max(r, g, b) - Math.min(r, g, b) < 40;

const out = [];
const seen = new Set();
for (const file of files) {
  const root = postcss.parse(fs.readFileSync(file, 'utf8'), { from: file });
  root.walkRules((rule) => {
    if (/data-theme="console"|data-theme="paper"|^:root|::selection|@keyframes/.test(rule.selector)) return;
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const decls = [];
    let hasColouredBg = false;
    rule.walkDecls(/^background/, (d) => { for (const c of d.value.match(COLOR) || []) { const rgb = rgbOf(c); if (rgb && !isNeutral(rgb) && lum(rgb) > 0.25) hasColouredBg = true; } });
    rule.walkDecls((d) => {
      const lits = d.value.match(COLOR) || [];
      if (!lits.length) return;
      if (/^background(-color|-image)?$/.test(d.prop)) {
        const dark = lits.map(rgbOf).filter(Boolean).filter((rgb) => lum(rgb) < 0.16);
        if (!dark.length || hasColouredBg) return;
        const darkest = Math.min(...dark.map(lum));
        const alphaOnly = /^rgba\(\s*0[ ,]+0[ ,]+0/.test(d.value.trim());
        decls.push(`  background: ${alphaOnly ? 'rgba(20, 24, 31, 0.28)' : darkest < 0.035 ? 'var(--bg)' : 'var(--panel)'};`);
      } else if (/^border(-top|-bottom|-left|-right)?(-color)?$/.test(d.prop)) {
        if (lits.map(rgbOf).filter(Boolean).some((rgb) => lum(rgb) < 0.16 && isNeutral(rgb))) decls.push(`  ${d.prop}: ${d.value.replace(COLOR, (c) => { const rgb = rgbOf(c); return rgb && lum(rgb) < 0.16 && isNeutral(rgb) ? 'var(--line)' : c; })};`);
      } else if (d.prop === 'box-shadow') {
        if (/rgba\(\s*0[ ,]+0[ ,]+0/.test(d.value)) decls.push(`  box-shadow: ${d.value.replace(/rgba\(\s*0[ ,]+0[ ,]+0[ ,]+([\d.]+)\)/g, (_, a) => `rgba(20, 24, 31, ${(+a * 0.3).toFixed(2)})`)};`);
      } else if (d.prop === 'color') {
        const rgb = rgbOf(lits[0]);
        if (rgb && lum(rgb) > 0.8 && isNeutral(rgb) && !hasColouredBg) decls.push('  color: var(--text);');
      }
    });
    if (!decls.length) return;
    const sel = rule.selector.split(',').map((s) => `${P} ${s.trim()}`).join(',\n');
    let block = `${sel} {\n${[...new Set(decls)].join('\n')}\n}`;
    let p = rule.parent;
    while (p && p.type === 'atrule') { if (p.name === 'media' || p.name === 'container' || p.name === 'supports') block = `@${p.name} ${p.params} {\n${block}\n}`; p = p.parent; }
    if (seen.has(block)) return;
    seen.add(block);
    out.push(`/* ${path.relative(SRC, file)}:${rule.source.start.line} */\n${block}`);
  });
}
fs.writeFileSync(OUT, `/* GENERATED by web/scripts/gen-paper.cjs — do not edit by hand. Light-face overrides for
   rules that hard-code dark colours. Tokens for the light face live in pass10-bridge.css. */\n\n${out.join('\n\n')}\n`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${out.length} rules from ${files.length} files`);
